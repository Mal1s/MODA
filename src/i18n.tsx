const dictionaries: Record<Language, Dict> = { ru, en };

interface I18nContextValue {
  lang: Language;
  setLang: (lang: Language) => void;
  t: (key: string) => string;
}

const I18nContext = createContext<I18nContextValue>({
  lang: 'ru',
  setLang: () => {},
  t: (key: string) => key,
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Language>(() => {
    const saved = typeof localStorage !== 'undefined' ? localStorage.getItem('fc-lang') : null;
    return saved === 'en' || saved === 'ru' ? saved : 'ru';
  });

  const setLang = (next: Language) => {
    setLangState(next);
    try { localStorage.setItem('fc-lang', next); } catch { /* ignore */ }
  };

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const t = (key: string) => dictionaries[lang][key] ?? key;

  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
